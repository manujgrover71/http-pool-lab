var summaryColumns = []string{
	"variant", "ok/s", "failed", "p50", "p99", "p99 conn wait", "reused", "new conns/s",
	"live max", "TIME_WAIT caller", "caller CPU", "caller throttled", "server CPU",
	"server new conns/s", "TIME_WAIT server",
}

// variantRun is one results/<experiment>/<variant>/ directory, read from its meta.json.
type variantRun struct {
	exp, variant, started string
	dir                   string
	gomaxprocs            int
	cpuMax                string
}

type runMeta struct {
	Experiment string
	Variant    string
	Started    string
	Gomaxprocs int
	CPUMax     string `json:"cpu_max"`
}

// summarize writes results/summary.md: one table per experiment, variants in the order they ran.
func summarize(out string) error {
	metas, err := filepath.Glob(filepath.Join(out, "*", "*", "meta.json"))
	if err != nil {
		return err
	}
	var runs []variantRun
	for _, m := range metas {
		b, err := os.ReadFile(m)
		if err != nil {
			return err
		}
		var meta runMeta
		if err := json.Unmarshal(b, &meta); err != nil {
			return fmt.Errorf("%s: %w", m, err)
		}
		runs = append(runs, variantRun{
			exp:        meta.Experiment,
			variant:    meta.Variant,
			started:    meta.Started,
			dir:        filepath.Dir(m),
			gomaxprocs: meta.Gomaxprocs,
			cpuMax:     meta.CPUMax,
		})
	}
	slices.SortFunc(runs, byExperimentThenStart)

	var b strings.Builder
	b.WriteString("# Results\n\n")
	b.WriteString("Generated by `go run ./cmd/lab summary` from each run's raw files.\n")
	b.WriteString("Latencies are client-side, for successful requests. CPU is cores used\n")
	b.WriteString("on average over the run; throttled is the share of quota periods that\n")
	b.WriteString("ran out of quota. `-` means the file wasn't there.\n")
	cur := ""
	for _, r := range runs {
		if r.exp != cur {
			cur = r.exp
			fmt.Fprintf(
				&b, "\n## %s\n\nCaller: GOMAXPROCS %d, cpu.max `%s`.\n\n",
				cur, r.gomaxprocs, r.cpuMax,
			)
			b.WriteString("| " + strings.Join(summaryColumns, " | ") + " |\n")
			b.WriteString(strings.Repeat("|---", len(summaryColumns)) + "|\n")
		}
		s, err := stats(r.dir)
		if err != nil {
			return fmt.Errorf("%s: %w", r.dir, err)
		}
		fmt.Fprintf(&b, "| %s | %s |\n", r.variant, strings.Join(s, " | "))
	}
	path := filepath.Join(out, "summary.md")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Print(b.String())
	return nil
}

func byExperimentThenStart(a, b variantRun) int {
	if c := strings.Compare(a.exp, b.exp); c != 0 {
		return c
	}
	return strings.Compare(a.started, b.started)
}

func stats(dir string) ([]string, error) {
	var cells []string

	ops, err := readTable(filepath.Join(dir, "ops.csv"))
	if err != nil {
		return nil, err
	}
	var totals, waits []float64
	var ok, reused int
	var first, last float64 = math.Inf(1), 0
	for i := range ops.rows {
		start := ops.f(i, "start_ms")
		first, last = min(first, start), max(last, start)
		waits = append(waits, ops.f(i, "wait_us"))
		if ops.s(i, "err") == "" {
			ok++
			totals = append(totals, ops.f(i, "total_us"))
			if ops.s(i, "reused") == "true" {
				reused++
			}
		}
	}
	secs := max(last-first, 1) / 1000
	cells = append(
		cells, num(float64(ok)/secs), strconv.Itoa(len(ops.rows)-ok), dur(pct(totals, 50)),
		dur(pct(totals, 99)), dur(pct(waits, 99)), share(float64(reused), float64(ok)),
	)

	conns, err := readTable(filepath.Join(dir, "conns.csv"))
	switch {
	case errors.Is(err, fs.ErrNotExist):
		cells = append(cells, "-", "-", "-")
	case err != nil:
		return nil, err
	default:
		cells = append(
			cells, num(conns.mean("opened")), num(conns.max("live")), count(conns.max("timewait")),
		)
	}

	cpu, err := readTable(filepath.Join(dir, "cpu.csv"))
	switch {
	case errors.Is(err, fs.ErrNotExist):
		cells = append(cells, "-", "-")
	case err != nil:
		return nil, err
	default:
		cells = append(cells, cores(cpu), throttled(cpu))
	}

	srv, err := readTable(filepath.Join(dir, "server.csv"))
	switch {
	case errors.Is(err, fs.ErrNotExist):
		cells = append(cells, "-", "-", "-")
	case err != nil:
		return nil, err
	default:
		opened := "-"
		if len(srv.rows) > 1 {
			opened = num(srv.delta("opened") / (srv.delta("t_ms") / 1000))
		}
		cells = append(cells, cores(srv), opened, count(srv.max("timewait")))
	}
	return cells, nil
}

func cores(t *table) string {
	if len(t.rows) < 2 {
		return "-"
	}
	return fmt.Sprintf("%.2f", t.delta("usage_usec")/(t.delta("t_ms")*1000))
}

func throttled(t *table) string {
	if len(t.rows) < 2 {
		return "-"
	}
	return share(t.delta("nr_throttled"), t.delta("nr_periods"))
}
